// Builds supabase/setup.sql (schema, security rules, demo accounts and sample data).
// Usage: node tools/make-setup-sql.js
const fs = require('fs');
const path = require('path');
require(path.join(__dirname, '..', 'assets', 'js', 'seed.js'));
const { seed, DEMO } = globalThis.NL_SEED;

const daysFromNow = (d, h = 10, m = 0) => { const t = new Date(); t.setUTCDate(t.getUTCDate() + d); t.setUTCHours(h - 8, m, 0, 0); return t.toISOString(); };
const data = seed(daysFromNow);

// Seeded clients get fixed ids so their matters link up. They start as "pending" (no login);
// creating the sample client's login below claims Sarah's record automatically.
const IDS = { u_sarah: 'b2e1d4f3-5c6e-4d7f-9a81-223344556677', u_wei: 'c3f2e5a4-6d7f-4e8a-ab92-334455667788', u_omar: 'd4a3f6b5-7e8a-4f9b-bca3-445566778899' };
const json = (o) => '$j$' + JSON.stringify(o) + '$j$::jsonb';
const sqlStr = (s) => (s == null ? 'null' : "'" + String(s).replace(/'/g, "''") + "'");
const rows = [];
const row = (coll, id, clientId, obj) => rows.push(`    (${sqlStr(coll)}, ${sqlStr(id)}, ${clientId ? sqlStr(clientId) + '::uuid' : 'null'}, ${json(obj)})`);

row('settings', 'firm', null, data.settings);
for (const u of data.users) {
  if (u.role !== 'client') continue;
  const { password, id, ...rest } = u;
  row('users', IDS[id], IDS[id], { ...rest, pending: true });
}
for (const coll of ['documents', 'messages', 'invoices', 'appointments']) {
  for (const x of data[coll]) { const { id, ...rest } = x; row(coll, id, IDS[x.clientId], { ...rest, clientId: IDS[x.clientId] }); }
}
for (const m of data.matters) {
  const { id, updates, ...rest } = m;
  const pub = updates.filter((u) => !u.internal), priv = updates.filter((u) => u.internal);
  row('matters', id, IDS[m.clientId], { ...rest, clientId: IDS[m.clientId], updates: pub });
  if (priv.length) row('notes', id, null, { updates: priv });
}
for (const e of data.enquiries) { const { id, ...rest } = e; row('enquiries', id, null, rest); }

const staff = data.users.find((u) => u.role === 'admin');
const staffExtra = { title: staff.title, tz: staff.tz, currency: staff.currency, lang: staff.lang };

const sql = `-- ============================================================================
-- Nisrin Law — Supabase setup
-- Paste this whole file into Supabase → SQL Editor → New query → Run.
-- Safe to run again: it only adds demo accounts and sample data if none exist yet.
-- Generated by tools/make-setup-sql.js on ${new Date().toISOString().slice(0, 10)}.
-- ============================================================================

-- 1. One table holds every record (enquiries, clients, matters, messages, …) as JSON.
create table if not exists public.records (
  coll       text not null,
  id         text not null,
  client_id  uuid,
  data       jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  primary key (coll, id)
);
create index if not exists records_client_idx on public.records (client_id);

-- 2. Who is staff?
create or replace function public.nl_is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.records where coll = 'users' and id = auth.uid()::text and data->>'role' = 'admin');
$$;

-- 3. Security rules.
alter table public.records enable row level security;
drop policy if exists staff_all       on public.records;
drop policy if exists read_settings   on public.records;
drop policy if exists client_read     on public.records;
drop policy if exists client_insert   on public.records;
drop policy if exists client_update   on public.records;
drop policy if exists public_enquiry  on public.records;

-- Staff: full access.
create policy staff_all on public.records for all to authenticated
  using (public.nl_is_staff()) with check (public.nl_is_staff());
-- Everyone: firm settings (contact details, exchange rates).
create policy read_settings on public.records for select to anon, authenticated
  using (coll = 'settings');
-- Clients: only their own records, never internal notes.
create policy client_read on public.records for select to authenticated
  using (client_id = auth.uid() and coll <> 'notes');
-- Clients may send messages, upload documents and request appointments for themselves.
create policy client_insert on public.records for insert to authenticated
  with check (client_id = auth.uid() and (
    (coll = 'messages' and data->>'from' = 'client') or
    (coll = 'documents' and data->>'by' = 'client') or
    (coll = 'appointments' and data->>'status' = 'requested')));
-- Clients may edit their own profile (never their role) and mark messages as read.
create policy client_update on public.records for update to authenticated
  using (client_id = auth.uid() and coll in ('users', 'messages'))
  with check (client_id = auth.uid() and (
    coll = 'messages' or
    (coll = 'users' and id = auth.uid()::text and data->>'role' = 'client' and not (data ? 'pending'))));
-- Anyone (signed in or not) may submit an enquiry from the website — but cannot read enquiries.
create policy public_enquiry on public.records for insert to anon, authenticated
  with check (coll = 'enquiries' and client_id is null and data->>'status' = 'new');

grant select, insert, update, delete on public.records to authenticated;
grant select, insert on public.records to anon;

-- 4. New sign-ups become clients. If staff already created a client record with the same
--    email, the new login takes over that record and its matters.
create or replace function public.nl_handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  pend public.records%rowtype;
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  prof jsonb;
begin
  prof := jsonb_strip_nulls(jsonb_build_object(
    'name', meta->>'name', 'company', meta->>'company', 'country', meta->>'country', 'phone', meta->>'phone',
    'tz', meta->>'tz', 'currency', meta->>'currency', 'lang', meta->>'lang'));
  select * into pend from public.records
   where coll = 'users' and lower(data->>'email') = lower(new.email) and coalesce((data->>'pending')::boolean, false)
   limit 1;
  if found then
    update public.records
       set client_id = new.id,
           data = case when data ? 'clientId' then jsonb_set(data, '{clientId}', to_jsonb(new.id::text)) else data end
     where client_id = pend.client_id and coll <> 'users';
    update public.records
       set id = new.id::text, client_id = new.id, updated_at = now(),
           data = (pend.data - 'pending') || prof || jsonb_build_object('role', 'client', 'email', lower(new.email))
     where coll = 'users' and id = pend.id;
  else
    insert into public.records (coll, id, client_id, data) values ('users', new.id::text, new.id,
      jsonb_build_object('name', split_part(new.email, '@', 1), 'tz', 'Asia/Kuala_Lumpur', 'currency', 'MYR', 'lang', 'en',
                         'joined', to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
      || prof || jsonb_build_object('role', 'client', 'email', lower(new.email)));
  end if;
  return new;
end $$;
drop trigger if exists nl_on_auth_user_created on auth.users;
create trigger nl_on_auth_user_created after insert on auth.users
  for each row execute function public.nl_handle_new_user();

-- 5. Helper to create ready-to-use logins (run from the SQL Editor only).
--    Example — add another staff member:
--    select public.nl_create_account('name@nisrinlaw.com', 'StrongPassword#1', 'Full Name', 'admin', '{"title":"Senior Partner"}');
create or replace function public.nl_create_account(p_email text, p_password text, p_name text,
                                                    p_role text default 'client', p_extra jsonb default '{}'::jsonb)
returns uuid language plpgsql security definer set search_path = public, auth, extensions as $$
declare uid uuid := gen_random_uuid();
begin
  if exists (select 1 from auth.users where lower(email) = lower(p_email)) then
    raise notice 'Account % already exists — skipped', p_email;
    select id into uid from auth.users where lower(email) = lower(p_email);
    return uid;
  end if;
  insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
                          raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
                          confirmation_token, recovery_token, email_change_token_new, email_change)
  values ('00000000-0000-0000-0000-000000000000', uid, 'authenticated', 'authenticated', lower(p_email),
          extensions.crypt(p_password, extensions.gen_salt('bf')), now(),
          '{"provider":"email","providers":["email"]}'::jsonb, jsonb_build_object('name', p_name) || p_extra,
          now(), now(), '', '', '', '');
  insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (gen_random_uuid(), uid, uid::text,
          jsonb_build_object('sub', uid::text, 'email', lower(p_email), 'email_verified', true),
          'email', now(), now(), now());
  if p_role = 'admin' then
    update public.records set client_id = null, data = data || p_extra || jsonb_build_object('role', 'admin', 'name', p_name)
     where coll = 'users' and id = uid::text;
  end if;
  return uid;
end $$;
revoke all on function public.nl_create_account(text, text, text, text, jsonb) from public, anon, authenticated;

-- 6. Live updates (staff see new enquiries without refreshing).
do $rt$ begin
  alter publication supabase_realtime add table public.records;
exception when others then null;
end $rt$;

-- 7. Demo accounts and sample data (only on first run).
do $seed$ begin
  if not exists (select 1 from public.records where coll = 'users') then
    insert into public.records (coll, id, client_id, data) values
${rows.join(',\n')}
    on conflict do nothing;

    perform public.nl_create_account(${sqlStr(DEMO.staff.email)}, ${sqlStr(DEMO.staff.password)}, ${sqlStr(staff.name)}, 'admin', ${json(staffExtra)});
    perform public.nl_create_account(${sqlStr(DEMO.client.email)}, ${sqlStr(DEMO.client.password)}, 'Sarah Thompson', 'client', '{}'::jsonb);
  end if;
end $seed$;

-- Done. Sign in with:
--   Staff:  ${DEMO.staff.email}  /  ${DEMO.staff.password}
--   Client: ${DEMO.client.email} /  ${DEMO.client.password}
select coll, count(*) from public.records group by coll order by coll;
`;

const out = path.join(__dirname, '..', 'supabase', 'setup.sql');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, sql);
console.log('Wrote', out, `(${rows.length} sample records)`);
